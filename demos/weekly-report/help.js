const normalize = value => String(value ?? '').normalize('NFKC').toLowerCase().replace(/[^\p{L}\p{N}]/gu, '');

export function searchHelp(query) {
  const q = normalize(String(query ?? '').slice(0, 500));
  if (q.length < 2) return [];
  return HELP_ARTICLES.map(article => {
    let score = 0;
    const title = normalize(article.title);
    if (title.includes(q)) score += 14;
    for (const keyword of new Set(article.keywords.map(normalize))) {
      if (keyword === q) score += 12;
      else if (q.includes(keyword)) score += 6;
      else if (keyword.includes(q)) score += 2;
    }
    return { article, score };
  }).filter(result => result.score > 0).sort((a, b) => b.score - a.score).slice(0, 5);
}

export function answerHelp(query) {
  const raw = String(query ?? '').slice(0, 500);
  const q = normalize(raw);
  const blocked = /입금|이체|송금|세금|급여|회계|수익예측|매출예측|예상매출|예상이익|수익률|얼마벌|얼마나벌|메일발송|메일보내|이메일보내|이메일발송|이메일전송|메일전송/.test(q);
  const privateRequest = /(우리회사|다른회사|고객|보고서|비밀번호).*(조회해|알려줘|보여줘|찾아줘|얼마야)/.test(q);
  const scope = HELP_ARTICLES.find(article => article.id === 'scope') || HELP_ARTICLES[0];
  if (blocked || privateRequest) return {
    answer: '문서 기반 검색 도우미입니다. 입금·이체·세금 신고·매출 예측·이메일 발송이나 비공개 회사 자료 조회는 지원하지 않으며 어떤 작업도 실행하지 않았습니다. 고객·프로젝트 등록, CSV 연결 검사, 보고서 검수·승인, 승인본 다운로드와 전달 수동 기록의 사용 방법을 안내할 수 있습니다.',
    articles: [scope], matched: false,
  };
  const found = searchHelp(raw);
  if (!found.length) return {
    answer: '관련 도움말을 찾지 못했습니다. 고객 등록, CSV 양식, 승인, 버전, 다운로드처럼 기능 이름으로 검색해 주세요. 공개 도움말만 검색하며 회사 자료 조회나 업무 실행은 하지 않습니다.',
    articles: [], matched: false,
  };
  const article = found[0].article;
  return {
    answer: `${article.title}\n${article.body}\n${article.steps.map((step, index) => `${index + 1}. ${step}`).join('\n')}`,
    articles: found.map(result => result.article), matched: true,
  };
}
